#!/usr/bin/env bash
# Render the Homebrew formula for awspick from the release archives' checksums.
#
# usage: render-formula.sh <version> <dist-dir>
#   <dist-dir> holds awspick-<version>-<target>.tar.gz.sha256 for the four
#   macOS/Linux targets. The formula is written to stdout.
set -euo pipefail

if [[ $# -ne 2 ]]; then
  echo "usage: $0 <version> <dist-dir>" >&2
  exit 2
fi

version="$1"
dist="$2"

if [[ ! "${version}" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]]; then
  echo "version must look like 1.2.3, got '${version}'" >&2
  exit 2
fi

base="https://github.com/KKamJi98/aws-profile-pick/releases/download/v${version}"

sha() {
  local file="${dist}/awspick-${version}-$1.tar.gz.sha256"
  local sum
  sum="$(cut -d ' ' -f 1 "${file}")"
  if [[ ! "${sum}" =~ ^[0-9a-f]{64}$ ]]; then
    echo "bad checksum in ${file}" >&2
    exit 1
  fi
  printf '%s' "${sum}"
}

# Computed before the heredoc: an `exit 1` inside $(sha ...) there would only
# end the command substitution and still print a formula with an empty sum.
sum_mac_arm="$(sha aarch64-apple-darwin)"
sum_mac_intel="$(sha x86_64-apple-darwin)"
sum_linux_arm="$(sha aarch64-unknown-linux-musl)"
sum_linux_intel="$(sha x86_64-unknown-linux-musl)"

cat <<FORMULA
# Generated by KKamJi98/aws-profile-pick .github/workflows/release.yml. Do not edit here.
class Awspick < Formula
  desc "Pick an AWS profile from ~/.aws/config and set AWS_PROFILE in your shell"
  homepage "https://github.com/KKamJi98/aws-profile-pick"
  version "${version}"
  license "MIT"

  on_macos do
    on_arm do
      url "${base}/awspick-${version}-aarch64-apple-darwin.tar.gz"
      sha256 "${sum_mac_arm}"
    end
    on_intel do
      url "${base}/awspick-${version}-x86_64-apple-darwin.tar.gz"
      sha256 "${sum_mac_intel}"
    end
  end

  on_linux do
    on_arm do
      url "${base}/awspick-${version}-aarch64-unknown-linux-musl.tar.gz"
      sha256 "${sum_linux_arm}"
    end
    on_intel do
      url "${base}/awspick-${version}-x86_64-unknown-linux-musl.tar.gz"
      sha256 "${sum_linux_intel}"
    end
  end

  def install
    bin.install "awspick"
    generate_completions_from_executable(bin/"awspick", "--completions", shells: [:bash, :zsh, :fish])
  end

  test do
    assert_match "awspick #{version}", shell_output("#{bin}/awspick --version")
  end
end
FORMULA
